def main():
    with open(TARGET, "r", encoding="utf-8") as f:
        content = f.read()

    # keywords: [...] のパターンを見つけて、各キーワードのひらがな版を追加
    def add_hiragana(m):
        full = m.group(0)
        kw_content = m.group(1)

        if not kw_content.strip():
            return full

        # 既存キーワードをパース
        existing = re.findall(r'"([^"]*)"', kw_content)
        if not existing:
            return full

        to_add = []
        for kw in existing:
            if kw in KW_TO_HIRA and KW_TO_HIRA[kw]:
                hira = KW_TO_HIRA[kw]
                if hira not in existing and hira not in to_add:
                    to_add.append(hira)

        if not to_add:
            return full

        # 新しいキーワードを追加
        new_existing = existing + to_add

        # フォーマット
        if len(new_existing) <= 3:
            inner = ", ".join(f'"{kw}"' for kw in new_existing)
            return f"keywords: [{inner}]"
        else:
            lines = ",\n      ".join(f'"{kw}"' for kw in new_existing)
            return f"keywords: [\n      {lines},\n    ]"

    # keywords: [任意の中身] にマッチ (複数行対応)
    pattern = re.compile(r'keywords: \[((?:[^\]]*?))\]', re.DOTALL)
    new_content = pattern.sub(add_hiragana, content)

    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(new_content)

    # カウント
    old_count = len(re.findall(r'"[^"]*"', ''.join(re.findall(r'keywords: \[([^\]]*)\]', content, re.DOTALL))))
    new_count = len(re.findall(r'"[^"]*"', ''.join(re.findall(r'keywords: \[([^\]]*)\]', new_content, re.DOTALL))))
    print(f"✅ キーワード総数: {old_count} → {new_count} (+{new_count - old_count}個のひらがな読み追加)")


if __name__ == "__main__":
    main()
