export function getNodeDisplayInfoByLocid(locid: string): {
  name: string;
  position: string;
} | null {
  const location = LOCATIONS.find(
    (entry) => entry.locid === locid || entry.id === locid,
  );

  if (location) {
    return {
      name: location.name,
      position: location.position,
    };
  }

  return TRANSIT_NODE_META[locid] || null;
}

export function getLocationById(id: string): Location | null {
  return LOCATIONS.find((location) => location.id === id) || null;
}

